import { NextResponse } from "next/server";

// Без этого Next.js может статически закэшировать GET-роут ещё на
// этапе сборки — а проверка здоровья Railway должна отвечать 200
// каждый раз заново, независимо от состояния приложения.
export const dynamic = "force-dynamic";

/**
 * Технический адрес для проверки здоровья сервиса (Railway Healthcheck).
 * Специально исключён из middleware.ts (не требует пароля) — иначе
 * Railway никогда не получит 200 OK и будет считать каждый деплой
 * неудачным, откатывая его. Раньше эта же роль случайно легла на "/"
 * (главную страницу), но она сама требует входа по паролю и всегда
 * отдаёт 307 — отсюда и были неудачные деплои после добавления входа.
 */
export async function GET() {
  return NextResponse.json({ ok: true, service: "aoms-web", time: new Date().toISOString() });
}
